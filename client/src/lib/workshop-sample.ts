import type { ProductionQueueItem, ProductionQueueResponse } from "@shared/schema";
import { shipByCalendarDate, addShipByCalendarDays } from "@shared/ship-by";

function checklist(
  dealId: string,
  extra: Partial<ProductionQueueItem["fulfillment"]> = {},
): ProductionQueueItem["fulfillment"] {
  return {
    dealId,
    addressVerified: false,
    costsEntered: false,
    labelBought: false,
    trackingPasted: false,
    packingDone: false,
    trackingNumber: "",
    notes: "",
    completedCount: extra.completedCount ?? 0,
    totalCount: 5,
    readyPercent: extra.readyPercent ?? 0,
    shipReady: extra.shipReady ?? false,
    updatedAt: null,
    ...extra,
  };
}

function item(
  partial: Omit<ProductionQueueItem, "fulfillment" | "chaseDraft" | "addressSummary" | "shippingRequired"> &
    Partial<Pick<ProductionQueueItem, "fulfillment" | "chaseDraft" | "addressSummary" | "shippingRequired">>,
): ProductionQueueItem {
  return {
    chaseDraft: "",
    addressSummary: partial.addressSummary ?? "Portland, OR",
    shippingRequired: partial.shippingRequired ?? true,
    fulfillment: partial.fulfillment ?? checklist(partial.dealId),
    ...partial,
  };
}

